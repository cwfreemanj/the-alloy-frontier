import type { DamageType, EquipInfo, ForgeMode, GearBonuses, ItemFamily, MaterialId, Specialization } from './types';

export interface MaterialRequirement {
  materialId: MaterialId;
  quantity: number;
}

/** WeaponDefinition + CraftingRecipe (GDD 6.3), merged for the slice. */
export interface BlueprintDefinition {
  id: string;
  name: string;
  family: ItemFamily;
  /** Where it goes when equipped. Omitted: a one-handed main-hand weapon. See docs/equipment-contract.md. */
  equip?: EquipInfo;
  /** Weapons: overrides the family's default damage type. */
  damageType?: DamageType;
  tier: string;
  description: string;
  baseDamage: number;
  baseAttackSpeed: number;
  baseStagger: number;
  baseStaminaMultiplier: number;
  /** Materials consumed (primary + secondary + catalyst). */
  materials: MaterialRequirement[];
  buffer: { materialId: MaterialId; min: number; standardBatch: number };
  masteryRequirement: number;
  craftable: boolean;
  modes: ForgeMode[];
  allowedSpecializations: Specialization[];
  potentialImbuements: string[];
  /** Base blacksmith XP awarded by mode. */
  masteryXp: { quick: number; masterwork: number };
  /**
   * Armor and shields: defense before craftsmanship. The forge scales it the way it scales a weapon's
   * damage (smith, materials, flux, forge); the item's weapon stats stay neutral.
   */
  baseDefense?: number;
  /**
   * Accessories (Crafting): bonuses before craftsmanship, scaled like defense. With them, an item is made
   * at the workbench, not the anvil (see `branch`).
   */
  baseBonuses?: GearBonuses;
  /** The proficiency branch that makes it (docs/proficiency-tree.md). Omitted: Smithing, at the anvil. */
  branch?: 'smithing' | 'crafting';
  /** Colours for 2D drawings (forge preview, icons). */
  visual: { blade: string; edge: string; guard: string; grip: string; length: number; glow?: string };
  /**
   * The 3D look, made by the creative director's Model Workshop generator (equipment.js): its item type,
   * a shape and a material blend. Looks only: stats always come from this file and generate.ts.
   */
  look?: { type: string; shape?: string; blend?: string };
}

