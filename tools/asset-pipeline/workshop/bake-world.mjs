// Bakes the Model Workshop's Emberhold scene into packages/world/src/emberholdData.ts.
//
//   node tools/asset-pipeline/workshop/bake-world.mjs [scene.json]
//
// With no argument it bakes the workshop's default scene (world.js defaultScene()). Pass a scene
// exported from the workshop's World view ("Export scene") to bake an edited layout instead.
// The output is shared by the browser (visuals) and the world server (colliders), so both always
// agree on where every building, tree and rock stands.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { defaultScene, normalizeScene, generate } from './world.js';
import * as T from './terrain.js';
import { starterLibrary, buildModel, optimizeForGame, MaterialBank, DEFAULT_MATERIALS } from '../../../apps/web/src/world/workshop/core.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const out = path.join(repo, 'packages/world/src/emberholdData.ts');
const pumphouse = JSON.parse(fs.readFileSync(path.join(repo, 'apps/web/src/world/workshop/pumphouse.json'), 'utf8'));

const lib = new Map(starterLibrary().map((r) => [r.id, r]));
lib.set(pumphouse.id, pumphouse); // the team's saved version
const bank = new MaterialBank(DEFAULT_MATERIALS);
const radius = new Map();
function radiusOf(id) {
  if (!radius.has(id)) {
    const r = lib.get(id);
    if (!r) throw new Error(`Scene uses unknown model "${id}"`);
    const b = new THREE.Box3().setFromObject(optimizeForGame(buildModel(r, bank)));
    radius.set(id, Math.hypot(b.max.x - b.min.x, b.max.z - b.min.z) / 2);
  }
  return radius.get(id);
}

const arg = process.argv[2];
const scene = normalizeScene(arg ? JSON.parse(fs.readFileSync(arg, 'utf8')) : defaultScene());
const BACKDROP = new Set(['ridge_chunk', 'mesa_tile', 'hills_tile']);
const footprints = scene.placements.filter((p) => !BACKDROP.has(p.model)).map((p) => ({ x: p.x, z: p.z, r: radiusOf(p.model) * p.scale * 0.85 + 1 }));
const gen = generate(scene, footprints);

const models = [];
const idx = (m) => {
  let i = models.indexOf(m);
  if (i < 0) i = models.push(m) - 1;
  return i;
};
const r2 = (v) => Math.round(v * 100) / 100;
const yawOf = (v) => Math.round((((v % 360) + 360) % 360) * 10) / 10;

const statics = [];
const nodes = [];
let ore = 0;
let glass = 0;
for (const p of scene.placements) statics.push([idx(p.model), r2(p.x), r2(p.z), r2(p.y), yawOf(p.yaw), r2(p.scale)]);
for (const it of gen.items) {
  if (it.gen === 'nodes') continue; // the game's own resource nodes render these
  if (it.anchor) {
    // The heart of each generated seam is a real, minable node.
    const glassNode = it.model === 'ironglass_cluster';
    nodes.push({ id: glassNode ? `glass-g${++glass}` : `ore-g${++ore}`, material: glassNode ? 'ironglass' : 'iron_ore', x: r2(it.x), z: r2(it.z), scale: r2(it.scale), yaw: yawOf(it.yaw) });
    continue;
  }
  statics.push([idx(it.model), r2(it.x), r2(it.z), r2(it.y), yawOf(it.yaw), r2(it.scale)]);
}

// Sanity: nothing solid on top of an NPC, the anvil, spawns or a gameplay node.
const keep = [T.PLAYER_SPAWN, T.RESPAWN_POINT, T.TRAINING_POST, ...T.NPCS.map((n) => n.pos), ...T.ENEMY_SPAWNS.map((e) => e.pos), ...T.RESOURCE_NODES.map((n) => n.pos)];
for (const s of statics) {
  const m = models[s[0]];
  if (BACKDROP.has(m) || m === 'arena_floor' || m === 'shrub') continue;
  for (const k of keep) {
    const d = Math.hypot(s[1] - k.x, s[2] - k.z);
    if (d < Math.min(2.2, radiusOf(m) * s[5])) console.warn(`warning: ${m} at (${s[1]}, ${s[2]}) is ${d.toFixed(1)} m from a gameplay point (${k.x}, ${k.z})`);
  }
}

const rows = [];
for (let i = 0; i < statics.length; i += 6) rows.push(`  ${statics.slice(i, i + 6).map((s) => s.join(', ')).join(', ')},`);
const src = `// GENERATED by tools/asset-pipeline/workshop/bake-world.mjs from the Model Workshop scene
// "${scene.name}" (generator seed ${scene.generators.seed}). Do not edit by hand: re-run the bake.

/** Workshop model ids used by the baked scene. */
export const EMBERHOLD_MODELS = ${JSON.stringify(models)} as const;
export type EmberholdModel = (typeof EMBERHOLD_MODELS)[number];

/** Static world items, 6 numbers each: model index, x, z, y offset above terrain, yaw (degrees), scale. */
export const EMBERHOLD_STATIC: readonly number[] = [
${rows.join('\n')}
];

/** Extra minable nodes at the heart of each generated ore / crystal seam. */
export const EMBERHOLD_SEAMS = ${JSON.stringify(nodes).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')} as const;

/** Atmosphere preset the scene was authored under. */
export const EMBERHOLD_TIME = ${JSON.stringify(scene.atmosphere.time)};
`;
fs.writeFileSync(out, src);
const counts = {};
for (const s of statics) counts[models[s[0]]] = (counts[models[s[0]]] ?? 0) + 1;
console.log(`baked ${statics.length} static items, ${nodes.length} seam nodes (${ore} ore, ${glass} glass) -> ${path.relative(repo, out)} (${(src.length / 1024).toFixed(1)} KB)`);
console.log(counts);
